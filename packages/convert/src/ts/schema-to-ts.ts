const INT32_MIN = -2147483648;
const INT32_MAX = 2147483647;

type Kind = "atom" | "union" | "inter";
interface TypeText {
  text: string;
  kind: Kind;
  /** 只在 kind 为 union 时存在. */
  members?: TypeText[];
}

/** 注释中的一个标签; `key` 是它对应的 schema 关键字, 用于按规范化顺序排列. */
interface DocTag {
  key: string;
  lines: string[];
}

/** tag: 定义或属性, 可写 JSDoc; nested: 数组元素或联合分支, 不能写 JSDoc; lift: 数组元素, 枚举标签可上提到数组属性. */
type Position = "tag" | "nested" | "lift";

interface Rendered {
  type: TypeText;
  /** 节点本身, 或上提自数组元素的枚举标签. */
  titles: Record<string, string> | undefined;
  /** 同 titles, 取枚举成员的 description. */
  descriptions?: Record<string, string> | undefined;
  /** 可区分联合各分支的 title, 写成 `@branchTitles`; 没有 title 的分支为 null. */
  branchTitles?: (string | null)[] | undefined;
  /** 节点为整数且不是枚举或常量. */
  integer: boolean;
  /** 数组元素节点自身的 x-ui, 上提到数组属性. */
  ui?: JsonSchemaObject | undefined;
  /** 数组(逐层)元素的 x-ui, 下标为层级; 写成数组属性上的 `@itemUi` `@itemWidget`. */
  itemUis?: (JsonSchemaObject | undefined)[] | undefined;
  /** 数组(逐层)元素或可空包装内层对象的 `@closed` `@decimalRange`, 上提到所在属性. */
  valueTags?: DocTag[] | undefined;
}

interface Context {
  names: Map<string, string>;
  diagnostics: Diagnostic[];
  typia: boolean;
  typiaIdent: string;
  typiaUsed: boolean;
}

const atom = (text: string): TypeText => ({ text, kind: "atom" });

function union(members: TypeText[]): TypeText {
  const parts: TypeText[] = [];
  for (const m of members.flatMap((m) => m.members ?? [m])) {
    if (!parts.some((p) => p.text === m.text)) parts.push(m);
  }
  if (parts.length === 0) return atom("never");
  if (parts.length === 1) return parts[0] as TypeText;
  const text = parts.map((p) => (p.kind === "inter" ? `(${p.text})` : p.text)).join(" | ");
  return { text, kind: "union", members: parts };
}

function intersect(base: TypeText, tags: string[]): TypeText {
  if (tags.length === 0) return base;
  const head = base.kind === "atom" ? base.text : `(${base.text})`;
  return { text: [head, ...tags].join(" & "), kind: "inter" };
}

function arrayOf(element: TypeText): TypeText {
  return atom(element.kind === "atom" ? `${element.text}[]` : `(${element.text})[]`);
}

function literal(value: unknown): string | undefined {
  if (value === null) return "null";
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : undefined;
  if (typeof value === "boolean") return String(value);
  return undefined;
}

function isLabeledEnum(schema: JsonSchemaObject): boolean {
  const oneOf = schema.oneOf;
  return Array.isArray(oneOf) && oneOf.length > 0
    && oneOf.every((b) => isSchemaObject(b) && "const" in b && Object.keys(b).every((k) => ["const", "title", "description"].includes(k)));
}

/** 编译器为 money/bigint 生成的封闭值对象; 只有它的 x-decimalRange 写成 `@decimalRange`. */
function isBuiltinValue(schema: JsonSchemaObject): boolean {
  const props = schema.properties;
  if (schema.additionalProperties !== false || !isSchemaObject(props) || !isSchemaObject(props.value)) return false;
  const kind = props.type;
  return isSchemaObject(kind) && (kind.const === "money" || kind.const === "bigint");
}

/**
 * 可空包装 `anyOf: [联合, {type: "null"}]`(编译器给联合加 `nullable: true` 的结果)中的内层联合; 写成 `(A | B) | null`,
 * 括号使 tsToSchema 能还原两层结构, 去掉括号会被拍平为 `anyOf [A, B, null]`.
 */
function nullableUnionInner(branches: JsonSchema[]): JsonSchemaObject | undefined {
  const [inner, tail] = branches;
  if (branches.length !== 2 || !isSchemaObject(inner) || !isSchemaObject(tail)) return undefined;
  if (Object.keys(tail).length !== 1 || tail.type !== "null") return undefined;
  if (["$ref", "const", "enum", "allOf"].some((k) => k in inner)) return undefined;
  return Array.isArray(inner.anyOf) || (Array.isArray(inner.oneOf) && !isLabeledEnum(inner)) ? inner : undefined;
}

/** 写成 `@closed` 的封闭对象; tsToSchema 读回的对象总带 `type: "object"`, 缺 type 的写出后不能往返. */
function isClosedObject(schema: JsonSchemaObject): boolean {
  return schema.additionalProperties === false && schema.type === "object";
}

/** 可空包装 `anyOf: [X, {type: "null"}]`; X 为对象时它的 `@closed` `@decimalRange` 上提到包装节点. */
function isNullableWrapper(branches: JsonSchema[]): boolean {
  const tail = branches[1];
  return branches.length === 2 && isSchemaObject(branches[0]) && isSchemaObject(tail) && Object.keys(tail).length === 1 && tail.type === "null";
}

/** 可区分联合各分支的 title, 没有 title 的为 null; 不是可区分联合或全无 title 时为 undefined. */
function discriminatedTitles(schema: JsonSchemaObject): (string | null)[] | undefined {
  const branches = schema.oneOf;
  if (!Array.isArray(branches) || !isDiscriminatedUnion(branches)) return undefined;
  const titles = branches.map((b) => (isSchemaObject(b) && typeof b.title === "string" ? b.title : null));
  return titles.some((t) => t !== null) ? titles : undefined;
}

/** 可区分联合: 各分支为对象, 有同一个必填字段取互不相同的常量. */
function isDiscriminatedUnion(branches: JsonSchema[]): boolean {
  if (branches.length < 2 || !branches.every((b) => isSchemaObject(b) && isSchemaObject(b.properties))) return false;
  const objects = branches as JsonSchemaObject[];
  const [first] = objects as [JsonSchemaObject];
  return Object.keys(first.properties as object).some((key) => {
    const values = objects.map((b) => {
      const prop = (b.properties as Record<string, JsonSchema>)[key];
      return Array.isArray(b.required) && b.required.includes(key) && isSchemaObject(prop) && "const" in prop
        ? JSON.stringify(prop.const) : undefined;
    });
    return values.every((v) => v !== undefined) && new Set(values).size === values.length;
  });
}

function typeNameFor(key: string, taken: Set<string>): string {
  let name = IDENTIFIER.test(key) ? key : key.replace(/[^A-Za-z0-9_$]/g, "_");
  if (/^[0-9]/.test(name)) name = `_${name}`;
  if (RESERVED_TYPE_NAMES.has(name)) name = `${name}_`;
  let candidate = name;
  for (let i = 2; taken.has(candidate); i++) candidate = `${name}${i}`;
  return candidate;
}

class Generator {
  constructor(private readonly ctx: Context) {}

  private warn(code: TsDiagnosticCode, pointer: JsonPointer, params?: Record<string, string>): void {
    this.ctx.diagnostics.push(tsDiagnostic(code, params, { location: { kind: "pointer", pointer } }));
  }

  private dropped(pointer: JsonPointer, keyword: string): void {
    this.warn("JOTL2002", pointer, { keyword });
  }

  /** 定义或属性节点: 类型文本与注释标签. */
  renderTagged(schema: JsonSchema, pointer: JsonPointer, indent: string): { type: TypeText; tags: DocTag[]; description?: string } {
    if (!isSchemaObject(schema)) return { type: this.renderBoolean(schema, pointer), tags: [] };
    const consumed = new Set<string>();
    const rendered = this.renderCore(schema, pointer, indent, "tag", consumed);
    const typia = this.typiaTags(schema, rendered, consumed);
    const type = this.applyTypia(rendered.type, typia);
    const tags = this.docTags(schema, pointer, consumed, rendered);
    this.reportLeftovers(schema, pointer, consumed);
    const description = typeof schema.description === "string" ? schema.description : undefined;
    return description === undefined ? { type, tags } : { type, tags, description };
  }

  /**
   * 不能写注释的节点: 只输出类型; typia 模式下约束改写为类型标签, 其余关键字告警丢弃.
   * carrier 为真时节点自身的 `@closed` `@decimalRange` 交给上层属性写出.
   */
  renderNested(
    schema: JsonSchema,
    pointer: JsonPointer,
    indent: string,
    position: "nested" | "lift",
    silent: readonly string[] = [],
    carrier = position === "lift",
  ): Rendered {
    if (!isSchemaObject(schema)) return { type: this.renderBoolean(schema, pointer), titles: undefined, integer: false };
    const consumed = new Set<string>(silent);
    const rendered = this.renderCore(schema, pointer, indent, position, consumed);
    const typia = this.typiaTags(schema, rendered, consumed);
    if (rendered.integer && !this.ctx.typia) this.dropped(pointer, "type: integer");
    const xUi = schema["x-ui"];
    const ui = position === "lift" && !consumed.has("x-ui") && isSchemaObject(xUi) && Object.keys(xUi).length > 0 ? xUi : undefined;
    if (ui !== undefined) consumed.add("x-ui");
    const own = carrier ? valueObjectTags(schema, consumed) : [];
    this.reportLeftovers(schema, pointer, consumed);
    const valueTags = own.length > 0 ? own : rendered.valueTags;
    return { ...rendered, type: this.applyTypia(rendered.type, typia), ui, valueTags };
  }

  private renderBoolean(schema: JsonSchema, pointer: JsonPointer): TypeText {
    if (typeof schema === "boolean") return atom(schema ? "unknown" : "never");
    this.ctx.diagnostics.push(tsDiagnostic("JOTL2001", undefined, { location: { kind: "pointer", pointer } }));
    return atom("unknown");
  }

  private renderCore(
    schema: JsonSchemaObject,
    pointer: JsonPointer,
    indent: string,
    position: Position,
    consumed: Set<string>,
  ): Rendered {
    const result = (
      type: TypeText,
      titles?: Record<string, string>,
      integer = false,
      descriptions?: Record<string, string>,
      itemUis?: (JsonSchemaObject | undefined)[],
      valueTags?: DocTag[],
    ): Rendered => ({ type, titles, integer, descriptions, itemUis, valueTags });

    const refs = refsOfAllOf(schema.allOf);
    if (refs !== undefined) {
      consumed.add("allOf");
      const { allOf: _, ...rest } = schema;
      const restRendered = this.renderCore(rest, pointer, indent, position, consumed);
      const parts = refs.map((ref, i) => this.renderRef(ref, appendPointer(pointer, "allOf", i, "$ref")).text);
      const restText = restRendered.type.kind === "union" ? `(${restRendered.type.text})` : restRendered.type.text;
      if (restText !== "unknown" || parts.length === 1) parts.push(restText);
      return { ...restRendered, type: { text: parts.join(" & "), kind: "inter" } };
    }
    if (typeof schema.$ref === "string") {
      consumed.add("$ref");
      return result(this.renderRef(schema.$ref, appendPointer(pointer, "$ref")));
    }
    if ("const" in schema) {
      consumed.add("const").add("type");
      return result(this.renderLiteralUnion([schema.const], appendPointer(pointer, "const")));
    }
    if (Array.isArray(schema.enum)) {
      consumed.add("enum").add("type");
      return result(this.renderLiteralUnion(schema.enum, appendPointer(pointer, "enum")));
    }
    if (Array.isArray(schema.oneOf) && isLabeledEnum(schema)) {
      consumed.add("oneOf").add("type");
      const branches = schema.oneOf as JsonSchemaObject[];
      const titles: Record<string, string> = {};
      const descriptions: Record<string, string> = {};
      branches.forEach((b, i) => {
        if (typeof b.title === "string") titles[enumTitleKey(b.const)] = b.title;
        if (typeof b.description === "string") descriptions[enumTitleKey(b.const)] = b.description;
        else if ("description" in b) this.dropped(appendPointer(pointer, "oneOf", i), "description");
      });
      const hasTitles = Object.keys(titles).length > 0;
      const hasDescriptions = Object.keys(descriptions).length > 0;
      if (hasTitles && position === "nested") this.dropped(pointer, "oneOf[].title");
      if (hasDescriptions && position === "nested") this.dropped(pointer, "oneOf[].description");
      const type = this.renderLiteralUnion(branches.map((b) => b.const), appendPointer(pointer, "oneOf"));
      const tagged = position !== "nested";
      return result(type, hasTitles && tagged ? titles : undefined, false, hasDescriptions && tagged ? descriptions : undefined);
    }
    const branchesKey = Array.isArray(schema.oneOf) ? "oneOf" : Array.isArray(schema.anyOf) ? "anyOf" : undefined;
    if (branchesKey !== undefined) {
      consumed.add(branchesKey);
      const branches = schema[branchesKey] as JsonSchema[];
      const inner = branchesKey === "anyOf" ? nullableUnionInner(branches) : undefined;
      const innerType = inner === undefined ? undefined : this.renderNested(inner, appendPointer(pointer, "anyOf", 0), indent, "nested").type;
      if (inner !== undefined && innerType?.kind === "union") {
        const head = atom(`(${innerType.text})`);
        const type: TypeText = { text: `${head.text} | null`, kind: "union", members: [head, atom("null")] };
        return { ...result(type), branchTitles: position === "tag" ? discriminatedTitles(inner) : undefined };
      }
      if (innerType !== undefined) {
        return result(union([innerType, this.renderNested(branches[1] as JsonSchema, appendPointer(pointer, "anyOf", 1), indent, "nested").type]));
      }
      const discriminated = branchesKey === "oneOf" && isDiscriminatedUnion(branches);
      const silent = discriminated ? ["title"] : [];
      const carrier = branchesKey === "anyOf" && position !== "nested" && isNullableWrapper(branches);
      const rendered = branches.map((b, i) => this.renderNested(b, appendPointer(pointer, branchesKey, i), indent, "nested", silent, carrier && i === 0));
      const type = union(rendered.map((r) => r.type));
      const branchTitles = branches.map((b) => (isSchemaObject(b) && typeof b.title === "string" ? b.title : null));
      const tagged = discriminated && position === "tag" && branchTitles.some((t) => t !== null);
      return { ...result(type), branchTitles: tagged ? branchTitles : undefined, valueTags: carrier ? rendered[0]?.valueTags : undefined };
    }

    const declared = schema.type;
    const types = Array.isArray(declared) ? declared : typeof declared === "string" ? [declared] : [];
    if (declared !== undefined) consumed.add("type");
    if (types.length === 0) {
      if (isSchemaObject(schema.properties) || "additionalProperties" in schema) {
        return result(this.renderObject(schema, pointer, indent, consumed));
      }
      if ("items" in schema || "prefixItems" in schema) return this.renderArray(schema, pointer, indent, position, consumed);
      return result(atom("unknown"));
    }
    let titles: Record<string, string> | undefined;
    let descriptions: Record<string, string> | undefined;
    let itemUis: (JsonSchemaObject | undefined)[] | undefined;
    let valueTags: DocTag[] | undefined;
    const members = types.map((t): TypeText => {
      switch (t) {
        case "string":
        case "number":
        case "boolean":
        case "null":
          return atom(t);
        case "integer":
          return atom("number");
        case "array": {
          const array = this.renderArray(schema, pointer, indent, position, consumed);
          titles = array.titles;
          descriptions = array.descriptions;
          itemUis = array.itemUis;
          valueTags = array.valueTags;
          return array.type;
        }
        case "object":
          return this.renderObject(schema, pointer, indent, consumed);
        default:
          this.dropped(pointer, `type: ${String(t)}`);
          return atom("unknown");
      }
    });
    return result(union(members), titles, types.includes("integer"), descriptions, itemUis, valueTags);
  }

  private renderRef(ref: string, pointer: JsonPointer): TypeText {
    const key = defKeyOfRef(ref);
    const name = key === undefined ? undefined : this.ctx.names.get(key);
    if (name === undefined) {
      this.warn("JOTL2003", pointer, { ref });
      return atom("unknown");
    }
    return atom(name);
  }

  private renderLiteralUnion(values: unknown[], pointer: JsonPointer): TypeText {
    return union(values.map((v, i) => {
      const text = literal(v);
      if (text !== undefined) return atom(text);
      this.warn("JOTL2005", appendPointer(pointer, i), { value: JSON.stringify(v) });
      return atom("unknown");
    }));
  }

  private renderArray(
    schema: JsonSchemaObject,
    pointer: JsonPointer,
    indent: string,
    position: Position,
    consumed: Set<string>,
  ): Rendered {
    consumed.add("items").add("prefixItems");
    const items = schema.items;
    const elementPosition = position === "nested" ? "nested" : "lift";
    if (Array.isArray(schema.prefixItems)) {
      const elements = schema.prefixItems.map((s, i) =>
        this.renderNested(s, appendPointer(pointer, "prefixItems", i), indent, "nested").type.text);
      if (items === undefined || items === true) elements.push("...unknown[]");
      else if (items !== false) elements.push(`...${arrayOf(this.renderNested(items, appendPointer(pointer, "items"), indent, "nested").type).text}`);
      return { type: atom(`[${elements.join(", ")}]`), titles: undefined, integer: false };
    }
    if (items === undefined) return { type: atom("unknown[]"), titles: undefined, integer: false };
    if (items === false) return { type: atom("[]"), titles: undefined, integer: false };
    const element = this.renderNested(items, appendPointer(pointer, "items"), indent, elementPosition);
    const itemUis = [element.ui, ...(element.itemUis ?? [])];
    return {
      type: arrayOf(element.type),
      titles: element.titles,
      descriptions: element.descriptions,
      integer: false,
      itemUis: itemUis.some((u) => u !== undefined) ? itemUis : undefined,
      valueTags: element.valueTags,
    };
  }

  private renderObject(schema: JsonSchemaObject, pointer: JsonPointer, indent: string, consumed: Set<string>): TypeText {
    const members = this.renderMembers(schema, pointer, indent + INDENT, consumed);
    return atom(members.length === 0 ? "{}" : `{\n${members.join("\n")}\n${indent}}`);
  }

  /** 对象的属性与索引签名, 每项一行或多行(含注释); 返回的行已带缩进. */
  renderMembers(schema: JsonSchemaObject, pointer: JsonPointer, indent: string, consumed: Set<string>): string[] {
    consumed.add("properties").add("required");
    // additionalProperties: false 留给 docTags 或上层属性写成 @closed; 都写不出时由 reportLeftovers 告警.
    const closed = schema.additionalProperties === false;
    if (!closed) consumed.add("additionalProperties");
    const lines: string[] = [];
    const propertyTypes: TypeText[] = [];
    const required = Array.isArray(schema.required) ? schema.required : [];
    const properties = isSchemaObject(schema.properties) ? (schema.properties as Record<string, JsonSchema>) : {};
    for (const [key, property] of Object.entries(properties)) {
      const propPointer = appendPointer(pointer, "properties", key);
      const rendered = this.renderTagged(property, propPointer, indent);
      lines.push(...renderDoc(indent, rendered.description, rendered.tags));
      const name = IDENTIFIER.test(key) ? key : JSON.stringify(key);
      const optional = required.includes(key) ? "" : "?";
      lines.push(`${indent}${name}${optional}: ${rendered.type.text};`);
      propertyTypes.push(optional === "" ? rendered.type : union([rendered.type, atom("undefined")]));
    }
    for (const key of required) {
      if (!(key in properties)) this.dropped(appendPointer(pointer, "required"), `required: ${key}`);
    }
    const additional = schema.additionalProperties;
    if (additional !== undefined && !closed) {
      if (typeof additional === "boolean") {
        this.dropped(pointer, `additionalProperties: ${String(additional)}`);
      } else {
        const value = this.renderNested(additional, appendPointer(pointer, "additionalProperties"), indent, "nested").type;
        lines.push(`${indent}[key: string]: ${indexSignatureType(value, propertyTypes)};`);
      }
    }
    return lines;
  }

  private typiaTags(schema: JsonSchemaObject, rendered: Rendered, consumed: Set<string>): string[] {
    if (!this.ctx.typia) return [];
    consumeTimestampBounds(schema, consumed);
    const t = this.ctx.typiaIdent;
    const out: string[] = [];
    const use = (keyword: string, tag: string): void => {
      consumed.add(keyword);
      out.push(`${t}.${tag}`);
    };
    if (rendered.integer) {
      const lower = schema.minimum ?? schema.exclusiveMinimum;
      const upper = schema.maximum ?? schema.exclusiveMaximum;
      const int32 = lower !== undefined && upper !== undefined && lower >= INT32_MIN && upper <= INT32_MAX;
      use("type", `Type<"${int32 ? "int32" : "int64"}">`);
    }
    for (const keyword of NUMERIC_KEYWORDS) {
      if (keyword === "minProperties" || keyword === "maxProperties") continue;
      const value = schema[keyword];
      if (typeof value === "number") use(keyword, `${keyword[0]?.toUpperCase()}${keyword.slice(1)}<${String(value)}>`);
    }
    if (typeof schema.pattern === "string") use("pattern", `Pattern<${JSON.stringify(schema.pattern)}>`);
    if (typeof schema.format === "string" && TYPIA_FORMATS.has(schema.format)) {
      use("format", `Format<${JSON.stringify(schema.format)}>`);
    }
    if (typeof schema.contentMediaType === "string") {
      use("contentMediaType", `ContentMediaType<${JSON.stringify(schema.contentMediaType)}>`);
    }
    if (typeof schema.uniqueItems === "boolean") use("uniqueItems", schema.uniqueItems ? "UniqueItems" : "UniqueItems<false>");
    const def = schema.default;
    const atomic = (v: unknown): boolean => ["string", "number", "boolean"].includes(typeof v);
    if (atomic(def) || (Array.isArray(def) && def.every(atomic))) use("default", `Default<${renderTypeLiteral(def)}>`);
    if (isSchemaObject(schema["x-ui"])) use("x-ui", `JsonSchemaPlugin<${renderTypeLiteral({ "x-ui": schema["x-ui"] })}>`);
    if (out.length > 0) this.ctx.typiaUsed = true;
    return out;
  }

  /** typia 标签只作用于非 null 部分: `T & tags.X` 中的 `null` 会被收窄为 never. */
  private applyTypia(type: TypeText, tags: string[]): TypeText {
    if (tags.length === 0) return type;
    const members = type.members ?? [type];
    if (!members.some((m) => m.text === "null")) return intersect(type, tags);
    const rest = members.filter((m) => m.text !== "null");
    if (rest.length === 0) return type;
    return union([intersect(union(rest), tags), atom("null")]);
  }

  private docTags(schema: JsonSchemaObject, pointer: JsonPointer, consumed: Set<string>, rendered: Rendered): DocTag[] {
    consumeTimestampBounds(schema, consumed);
    const tags: DocTag[] = [];
    const add = (key: string, lines: string[]): void => {
      tags.push({ key, lines });
    };
    const text = (keyword: string, tag: string): void => {
      const value = schema[keyword];
      if (value === undefined || consumed.has(keyword)) return;
      consumed.add(keyword);
      if (typeof value !== "string") return this.dropped(pointer, keyword);
      add(keyword, textTag(tag, value));
    };
    const flag = (keyword: string, tag: string): boolean => {
      const value = schema[keyword];
      if (value === undefined || consumed.has(keyword)) return false;
      consumed.add(keyword);
      if (value === true) {
        add(keyword, [`@${tag}`]);
        return true;
      }
      this.dropped(pointer, `${keyword}: ${JSON.stringify(value)}`);
      return false;
    };

    text("$comment", "privateRemarks");
    text("title", "title");
    consumed.add("description");
    if (rendered.integer && !this.ctx.typia) add("type", ["@asType integer"]);
    if (rendered.titles !== undefined) add("oneOf", [`@enumTitles ${encodeJson(rendered.titles)}`]);
    if (rendered.descriptions !== undefined) add("oneOf", [`@enumDescriptions ${encodeJson(rendered.descriptions)}`]);
    if (rendered.branchTitles !== undefined) add("oneOf", [`@branchTitles ${encodeJson(rendered.branchTitles)}`]);
    for (const keyword of TEXT_KEYWORDS) if (keyword !== "title") text(keyword, keyword);
    for (const [keyword, tag] of Object.entries(EXTENSION_TEXT_TAGS)) text(keyword, tag);
    for (const keyword of NUMERIC_KEYWORDS) {
      const value = schema[keyword];
      if (value === undefined || consumed.has(keyword)) continue;
      consumed.add(keyword);
      if (typeof value === "number") add(keyword, [`@${keyword} ${String(value)}`]);
      else this.dropped(pointer, keyword);
    }
    if (schema.pattern !== undefined && !consumed.has("pattern")) {
      consumed.add("pattern");
      if (typeof schema.pattern === "string") add("pattern", [`@pattern ${encodePattern(schema.pattern)}`]);
      else this.dropped(pointer, "pattern");
    }
    flag("uniqueItems", "uniqueItems");
    if ("default" in schema && !consumed.has("default")) {
      consumed.add("default");
      add("default", [`@defaultValue ${encodeJson(schema.default)}`]);
    }
    if (schema.examples !== undefined) {
      consumed.add("examples");
      if (Array.isArray(schema.examples)) {
        for (const example of schema.examples) {
          const lines = encodeExample(example);
          add("examples", lines.length === 1 ? [`@example ${lines[0] as string}`] : ["@example", ...lines]);
        }
      } else {
        this.dropped(pointer, "examples");
      }
    }
    const reason = schema["x-deprecatedReason"];
    if (schema.deprecated !== undefined) {
      consumed.add("deprecated");
      if (schema.deprecated === true) {
        if (typeof reason === "string") consumed.add("x-deprecatedReason");
        add("deprecated", textTag("deprecated", typeof reason === "string" ? reason : l10n(DEPRECATED_DEFAULT_TEXT, DEPRECATED_DEFAULT_TEXT_EN)));
      } else {
        this.dropped(pointer, `deprecated: ${JSON.stringify(schema.deprecated)}`);
      }
    }
    flag("readOnly", "readonly");
    flag("writeOnly", "writeOnly");
    const xUi = schema["x-ui"];
    if (xUi !== undefined && !consumed.has("x-ui")) {
      consumed.add("x-ui");
      if (!isSchemaObject(xUi)) this.dropped(pointer, "x-ui");
      else add("x-ui", [uiTag(xUi)]);
    }
    for (const ui of rendered.itemUis ?? []) add("x-ui", [uiTag(ui ?? {}, "item")]);
    tags.push(...valueObjectTags(schema, consumed), ...(rendered.valueTags ?? []));
    if (schema.errorMessage !== undefined) {
      consumed.add("errorMessage");
      add("errorMessage", [`@errorMessage ${encodeJson(schema.errorMessage)}`]);
    }
    return sortTags(tags);
  }

  private reportLeftovers(schema: JsonSchemaObject, pointer: JsonPointer, consumed: Set<string>): void {
    for (const key of Object.keys(schema)) if (!consumed.has(key)) this.dropped(pointer, key);
  }

  /** 接口声明: 接口本身不能挂 typia 标签, 节点上的约束全部写为 JSDoc. */
  renderInterface(schema: JsonSchemaObject, pointer: JsonPointer, documentTags: DocTag[]): { members: string[]; doc: string[] } {
    const consumed = new Set<string>(["type"]);
    const members = this.renderMembers(schema, pointer, INDENT, consumed);
    const tags = this.docTags(schema, pointer, consumed, { type: atom("object"), titles: undefined, integer: false });
    this.reportLeftovers(schema, pointer, consumed);
    const description = typeof schema.description === "string" ? schema.description : undefined;
    return { members, doc: renderDoc("", description, [...tags, ...documentTags]) };
  }
}

/** 封闭对象的 `@closed`, 以及 money/bigint 值对象的 `@decimalRange`; 写出的关键字记入 consumed. */
function valueObjectTags(schema: JsonSchemaObject, consumed: Set<string>): DocTag[] {
  const tags: DocTag[] = [];
  if (!isClosedObject(schema) || consumed.has("additionalProperties")) return tags;
  consumed.add("additionalProperties");
  tags.push({ key: "additionalProperties", lines: ["@closed"] });
  const range = schema["x-decimalRange"];
  if (range !== undefined && !consumed.has("x-decimalRange") && isBuiltinValue(schema) && isDecimalRange(range)) {
    consumed.add("x-decimalRange");
    tags.push({ key: "x-decimalRange", lines: [`@decimalRange ${encodeJson(range)}`] });
  }
  return tags;
}

/** 每项只含 `$ref` 的 allOf 写成交叉类型 `X & {...}`; 其余返回 undefined. */
function refsOfAllOf(allOf: unknown): string[] | undefined {
  if (!Array.isArray(allOf) || allOf.length === 0) return undefined;
  const refs = allOf.map((s) => (isSchemaObject(s) && Object.keys(s).length === 1 && typeof s.$ref === "string" ? s.$ref : undefined));
  return refs.every((r) => r !== undefined) ? refs : undefined;
}

/** `#/$defs/X` 形式的引用取 X; 其余返回 undefined. */
function defKeyOfRef(ref: string): string | undefined {
  if (!ref.startsWith("#")) return undefined;
  let fragment: string;
  try {
    fragment = decodeURIComponent(ref.slice(1));
  } catch {
    return undefined;
  }
  const tokens = tryParsePointer(fragment);
  return tokens?.length === 2 && tokens[0] === "$defs" ? tokens[1] : undefined;
}

/**
 * 属性类型(可选属性含 undefined)须可赋给索引签名类型: 不在额外类型中的并入联合, 额外类型加括号写在最前,
 * 以便 tsToSchema 区分(`(额外类型) | 属性类型...`).
 */
function indexSignatureType(value: TypeText, propertyTypes: TypeText[]): string {
  if (value.text === "unknown" || propertyTypes.length === 0) return value.text;
  const own = new Set((value.members ?? [value]).map((m) => m.text));
  const all = union(propertyTypes).members ?? [union(propertyTypes)];
  const extra = [...all.filter((m) => m.text !== "undefined"), ...all.filter((m) => m.text === "undefined")]
    .filter((m) => !own.has(m.text));
  // 不加外层括号时, `(A | B) | null` 的头部会被当作 `(额外类型)` 读回而丢掉 null.
  if (extra.length === 0) return value.kind === "union" && value.text.startsWith("(") ? `(${value.text})` : value.text;
  return [`(${value.text})`, ...extra.map((m) => (m.kind === "inter" ? `(${m.text})` : m.text))].join(" | ");
}

/** 只有 widget 时写 `@widget`, 否则 `@ui`; 数组元素的写 `@itemWidget` `@itemUi`, 空对象占位跳过的层级. */
function uiTag(xUi: JsonSchemaObject, prefix: "" | "item" = ""): string {
  const name = (tag: string) => (prefix === "" ? tag : `${prefix}${tag[0]?.toUpperCase()}${tag.slice(1)}`);
  if (Object.keys(xUi).length === 1 && typeof xUi.widget === "string" && WIDGET_NAME.test(xUi.widget)) {
    return `@${name("widget")} ${xUi.widget}`;
  }
  return `@${name("ui")} ${encodeJson(xUi)}`;
}

function textTag(tag: string, value: string): string[] {
  const [first = "", ...rest] = encodeText(value).split("\n");
  return [first === "" ? `@${tag}` : `@${tag} ${first}`, ...rest];
}

/** 编译器给时间戳节点(`x-valueFormat` 为 x X)补的 ±MAX_SAFE_INTEGER 上下界不写出, 读回时由 `@valueFormat` 补上. */
function consumeTimestampBounds(schema: JsonSchemaObject, consumed: Set<string>): void {
  const format = schema["x-valueFormat"];
  if (typeof format === "string" && isTimestampValueFormat(format) && schema.minimum === -Number.MAX_SAFE_INTEGER && schema.maximum === Number.MAX_SAFE_INTEGER) {
    consumed.add("minimum");
    consumed.add("maximum");
  }
}

function sortTags(tags: DocTag[]): DocTag[] {
  const order = Object.keys(orderKeywords(Object.fromEntries(tags.map((t) => [t.key, null])) as JsonSchemaObject));
  return [...tags].sort((a, b) => order.indexOf(a.key) - order.indexOf(b.key));
}

function renderDoc(indent: string, description: string | undefined, tags: DocTag[]): string[] {
  const body = description === undefined || description === "" ? [] : encodeText(description).split("\n");
  const lines = [...body, ...tags.flatMap((t) => t.lines)];
  if (lines.length === 0) return [];
  return [`${indent}/**`, ...lines.map((l) => (l === "" ? `${indent} *` : `${indent} * ${l}`)), `${indent} */`];
}

function isInterfaceShape(schema: JsonSchema): schema is JsonSchemaObject {
  if (!isSchemaObject(schema)) return false;
  if (["$ref", "const", "enum", "oneOf", "anyOf"].some((k) => k in schema)) return false;
  return schema.type === "object" || (schema.type === undefined && isSchemaObject(schema.properties));
}

/** 把 JSON Schema 2020-12 文档转为 TS 声明文件文本(docs/tag-protocol.md, fixtures README 的格式约定). */
export function schemaToTs(schema: JsonSchema, options: SchemaToTsOptions = {}): Result<string> {
  if (!isSchemaObject(schema)) return fail([tsDiagnostic("JOTL2001", undefined, { location: { kind: "pointer", pointer: "" } })]);
  const diagnostics: Diagnostic[] = [];
  const defs = isSchemaObject(schema.$defs) ? (schema.$defs as Record<string, JsonSchema>) : {};
  if (schema.$defs !== undefined && !isSchemaObject(schema.$defs)) {
    diagnostics.push(tsDiagnostic("JOTL2001", undefined, { location: { kind: "pointer", pointer: "/$defs" } }));
  }

  const names = new Map<string, string>();
  const taken = new Set<string>();
  for (const key of Object.keys(defs)) {
    const name = typeNameFor(key, taken);
    taken.add(name);
    names.set(key, name);
    if (name !== key) {
      diagnostics.push(tsDiagnostic("JOTL2004", { name: key, renamed: name }, {
        location: { kind: "pointer", pointer: appendPointer("/$defs", key) },
      }));
    }
  }
  const typiaIdent = taken.has("tags") ? "typiaTags" : "tags";
  const ctx: Context = { names, diagnostics, typia: options.typiaTags === true, typiaIdent, typiaUsed: false };
  const generator = new Generator(ctx);

  const declarations: string[] = [];
  let defaultExport: string | undefined;
  const requested = options.defaultExport !== undefined ? names.get(options.defaultExport) : undefined;
  // 根 x-ui 只含协议版本, 规则表与扩展组件模块时属于文档层面; 根 $id, 规则表与模块写成根类型上的 @id @rules @widgets.
  const rootXUi = schema["x-ui"];
  const documentXUi = isSchemaObject(rootXUi) && Object.keys(rootXUi).every((k) => k === "version" || k === "rules" || k === "widgets");
  const documentTags: DocTag[] = [];
  if (typeof schema.$id === "string") documentTags.push({ key: "$id", lines: textTag("id", schema.$id) });
  if (documentXUi && Object.hasOwn(rootXUi, "rules")) documentTags.push({ key: "x-ui", lines: [`@rules ${encodeJson(rootXUi.rules)}`] });
  if (documentXUi && Object.hasOwn(rootXUi, "widgets")) documentTags.push({ key: "x-ui", lines: [`@widgets ${encodeJson(rootXUi.widgets)}`] });
  const rootContent = Object.keys(schema).filter((k) => !ROOT_ONLY_KEYWORDS.has(k) && !(k === "x-ui" && documentXUi));
  const rootRef = rootContent.length === 1 && typeof schema.$ref === "string" ? schema.$ref : undefined;
  const rootKey = rootRef === undefined ? undefined : defKeyOfRef(rootRef);
  const rootTarget = rootKey === undefined ? undefined : names.get(rootKey);
  const rootName = rootTarget ?? (rootContent.length > 0 ? typeNameFor("Root", taken) : undefined);
  if (rootName !== undefined && requested !== undefined && requested !== rootName) {
    documentTags.unshift({ key: "$ref", lines: ["@root"] });
  }
  if (rootTarget !== undefined) {
    defaultExport = requested ?? rootTarget;
  } else if (rootName !== undefined) {
    taken.add(rootName);
    diagnostics.push(tsDiagnostic("JOTL2006", { name: rootName }, { location: { kind: "pointer", pointer: "" } }));
    const rootSchema: JsonSchemaObject = Object.fromEntries(rootContent.map((k) => [k, schema[k]]));
    declarations.push(renderDeclaration(generator, rootName, rootSchema, "", documentTags));
    defaultExport = requested ?? rootName;
  } else {
    // 没有默认导出时无处安放文档层面的标签, 与其他丢弃的关键字一样给出警告.
    for (const tag of documentTags) {
      const keyword = tag.key === "$id" ? "$id" : "x-ui.rules";
      diagnostics.push(tsDiagnostic("JOTL2002", { keyword }, { location: { kind: "pointer", pointer: "" } }));
    }
  }
  for (const [key, def] of Object.entries(defs)) {
    const name = names.get(key) as string;
    declarations.push(renderDeclaration(generator, name, def, appendPointer("/$defs", key), name === rootTarget ? documentTags : []));
  }

  const blocks: string[] = [];
  if (ctx.typiaUsed) {
    blocks.push(typiaIdent === "tags" ? `import { tags } from "typia";` : `import { tags as ${typiaIdent} } from "typia";`);
  }
  blocks.push(...declarations);
  if (defaultExport !== undefined) blocks.push(`export default ${defaultExport};`);
  if (declarations.length === 0 && defaultExport === undefined) blocks.push("export {};");
  const text = `${l10n(GENERATED_HEADER, GENERATED_HEADER_EN)}\n\n${blocks.join("\n\n")}\n`;
  return hasErrors(diagnostics) ? fail(diagnostics) : ok(text, diagnostics);
}

function renderDeclaration(generator: Generator, name: string, schema: JsonSchema, pointer: JsonPointer, documentTags: DocTag[]): string {
  if (isInterfaceShape(schema)) {
    const { members, doc } = generator.renderInterface(schema, pointer, documentTags);
    const body = members.length === 0 ? "{}" : `{\n${members.join("\n")}\n}`;
    return [...doc, `export interface ${name} ${body}`].join("\n");
  }
  const rendered = generator.renderTagged(schema, pointer, "");
  return [...renderDoc("", rendered.description, [...rendered.tags, ...documentTags]), `export type ${name} = ${rendered.type.text};`].join("\n");
}
