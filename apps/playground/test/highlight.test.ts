// 只读代码块的 JSON 与 TS 词法着色.
import { describe, expect, it } from "vitest";
import { type Token, tokenizeJson, tokenizeTs } from "../src/highlight.js";

const kindOf = (tokens: Token[], text: string, nth = 0) =>
	tokens.filter(t => t.text === text)[nth]?.kind;

describe("tokenizeJson", () => {
	const src =
		'{\n  "name": "a\\"b",\n  "n": -1.5e3,\n  "ok": true,\n  "x": null,\n  "list": [1, "s"]\n}';
	const tokens = tokenizeJson(src);

	it("拼回原文", () => {
		expect(tokens.map(t => t.text).join("")).toBe(src);
	});

	it("键, 字符串, 数字, 字面量与标点", () => {
		expect(kindOf(tokens, '"name"')).toBe("key");
		expect(kindOf(tokens, '"a\\"b"')).toBe("string");
		expect(kindOf(tokens, "-1.5e3")).toBe("number");
		expect(kindOf(tokens, "true")).toBe("literal");
		expect(kindOf(tokens, "null")).toBe("literal");
		expect(kindOf(tokens, '"s"')).toBe("string");
		expect(kindOf(tokens, "{")).toBe("punct");
	});
});

describe("tokenizeTs", () => {
	const src = [
		"// Generated by Jotl. Do not edit.",
		"",
		"/**",
		" * 店铺",
		" * @title 店铺",
		" * @pattern `^-?\\d+$`",
		" */",
		"export interface Shop {",
		'  type: "money";',
		"  intro?: string;",
		'  mode: "online" | "offline";',
		"  address?: Address;",
		"  count: number | null;",
		"  tags: readonly string[];",
		"}",
		"export type Id = 1 | 2;",
	].join("\n");
	const tokens = tokenizeTs(src);

	it("拼回原文", () => {
		expect(tokens.map(t => t.text).join("")).toBe(src);
	});

	it("注释与 JSDoc 标签", () => {
		expect(kindOf(tokens, "// Generated by Jotl. Do not edit.")).toBe("comment");
		expect(kindOf(tokens, "@title")).toBe("tag");
		expect(kindOf(tokens, "@pattern")).toBe("tag");
		expect(tokens.some(t => t.kind === "comment" && t.text.includes("`^-?\\d+$`"))).toBe(true);
	});

	it("关键字, 属性名, 类型, 字符串, 数字与字面量", () => {
		expect(kindOf(tokens, "export")).toBe("keyword");
		expect(kindOf(tokens, "interface")).toBe("keyword");
		expect(kindOf(tokens, "readonly")).toBe("keyword");
		expect(kindOf(tokens, "type")).toBe("key");
		expect(kindOf(tokens, "type", 1)).toBe("keyword");
		expect(kindOf(tokens, "intro")).toBe("key");
		expect(kindOf(tokens, "Shop")).toBe("type");
		expect(kindOf(tokens, "Address")).toBe("type");
		expect(kindOf(tokens, "string")).toBe("type");
		expect(kindOf(tokens, '"money"')).toBe("string");
		expect(kindOf(tokens, "1")).toBe("number");
		expect(kindOf(tokens, "null")).toBe("literal");
		expect(kindOf(tokens, "|")).toBe("punct");
	});
});
